def _sh(*a, **kw):
    return subprocess.run(list(a), capture_output=True, text=True, **kw)


def _docker():
    try:
        return _sh("docker", "info", timeout=10).returncode == 0
    except Exception:
        return False


def _or(*statements, port=OR_PORT):
    import oracledb
    conn = oracledb.connect(user="system", password=PASSWORD,
                            dsn=f"127.0.0.1:{port}/FREEPDB1")
    try:
        cur = conn.cursor()
        out = None
        for s in statements:
            cur.execute(s)
            out = cur.fetchall() if cur.description else out
        conn.commit()
        return out
    finally:
        conn.close()


def _pg(sql, name=PG, db="app"):
    got = _sh("docker", "exec", "-i", name, "psql", "-U", "postgres", "-d",
              db, "-At", "-v", "ON_ERROR_STOP=1", input=sql)
    assert got.returncode == 0, got.stderr
    return got.stdout.strip()


