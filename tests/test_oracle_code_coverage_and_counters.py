def _engine(tmp_path):
    from migkit.engines.hetero import HeteroEngine
    hop = Hop(name="orcov", engine="hetero",
              options={"source_engine": "oracle", "target_engine": "postgres",
                       "proof_sandbox": {
                           "source": {"host": "127.0.0.1",
                                      "port": SB_OR_PORT, "user": "system",
                                      "password": PASSWORD},
                           "target": {"host": "127.0.0.1",
                                      "port": SB_PG_PORT,
                                      "user": "postgres",
                                      "password": "test"}}},
              source=Endpoint(host="127.0.0.1", port=OR_PORT, user="system",
                              password=PASSWORD),
              target=Endpoint(host="127.0.0.1", port=PG_PORT,
                              user="postgres", password="test"),
              databases=["app"])
    hop.report_dir = lambda db=None: tmp_path
    return HeteroEngine(hop)


@pytest.fixture(scope="module")
def verdicts(servers, tmp_path_factory):
    tmp = tmp_path_factory.mktemp("orcov")
    got = _engine(tmp).prove_converted("app")
    return got, {v["routine"]: v for v in json.loads(
        (tmp / "code-proof.json").read_text())["verdicts"]}


def test_oracles_own_coverage_counts_the_blocks_reached(verdicts):
    _, by = verdicts
    v = by["function grade"]
    # every branch reached on both sides: ok, with both sides counted
    assert v["status"] == "ok", v
    assert "source: " in v["coverage"] and " blocks" in v["coverage"], v
    reached, blocks = v["coverage"].split("source: ")[1].split(" blocks")[
        0].split("/")
    assert int(reached) == int(blocks) > 1, v


def test_a_block_no_call_reached_is_named_by_its_line(verdicts):
    _, by = verdicts
    v = by["function short_of"]
    assert v["status"] == "warn", v
    assert "on the source, never reached: line" in v["reason"], v


def test_a_number_taken_from_an_identity_is_counted(verdicts):
    got, by = verdicts
    v = by["procedure add_item"]
    # the rows added are the same but for the numbers handed out, which
    # are never compared: the counter is
    assert v["status"] == "diff", v
    assert "items's counter moved 1 against 2" in v["reason"], v
    assert got.status == "diff", got.detail
    # the hop's own source was only read, and its identity not moved
    assert _or("select count(*), max(id) from app.items") == [(3, 3)]
