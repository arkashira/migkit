"""Oracle's routines proved with Oracle's own coverage and its identity
counters (backlog R11's leftovers).

A routine run on Oracle in the sandbox had no coverage and no counters:
its verdict said "coverage cannot be measured on oracle", and a version
that took a number from a table's identity it never used answered the
same, since the rows a call adds are compared without the numbers an
identity handed them. Now the server's own block coverage says which of
the source routine's blocks the calls reached, and each call is handed a
counter set from the fixture and read for how far it moved.

Oracle Free runs natively on arm64 from 23.5 (2 GB, 2 CPUs); two of it and
two PostgreSQL servers run in the machine's second VM
(`with_docker_lock.py --vm migkit`).
"""
