"""Stored code proved deeper (leapfrog research P6 and P8, backlog R11's
leftovers): on the calls the application really makes, over sequences of
calls, with the clock read at one instant on both sides, and with the
coverage of a routine that reads `ROW_COUNT()` measured through a copy
beside it.

Each routine here answers every call the old proof made alike on both
sides and differs only where the new one looks:
* `code_of` differs only past twelve characters - which no class pool,
  constant, fixture value or search draw reaches, and the application's
  own calls on the source's record do;
* `note` inserts once more on the source the second time it is given the
  same message - a single call from the fixture never shows it;
* `later` answers a second after the source - which the old five
  seconds' tolerance took for the same;
* `restock` reads `ROW_COUNT()`, so its coverage was never measured; now
  it is, through an instrumented copy held to it call by call.
"""
import json
import socket
import subprocess
import time

import pytest

from migkit.config import Endpoint, Hop

pytestmark = [pytest.mark.docker]

MY, PG = "migkit-test-depth-my", "migkit-test-depth-pg"
SB_MY, SB_PG = "migkit-test-depth-sbmy", "migkit-test-depth-sbpg"
MY_PORT, PG_PORT, SB_MY_PORT, SB_PG_PORT = 16290, 16291, 16292, 16293
PG_MAJOR = 17
#: the statement digests on: the application's calls are read from them
MY_FLAGS = ["--innodb-buffer-pool-size=16M",
            "--log-bin-trust-function-creators=1", "--event-scheduler=OFF"]
#: an order code as the application sends it: longer than the class
#: pools' texts and the search's draws, and no constant of any body
CODE = "ORDER-2026-000123"


def _sh(*a, **kw):
    return subprocess.run(list(a), capture_output=True, text=True, **kw)


def _docker():
    try:
        return _sh("docker", "info", timeout=10).returncode == 0
    except Exception:
        return False


def _pg(sql, name=PG, db="depth"):
    got = _sh("docker", "exec", "-i", name, "psql", "-U", "postgres", "-d",
              db, "-At", "-v", "ON_ERROR_STOP=1", input=sql)
    assert got.returncode == 0, got.stderr
    return got.stdout.strip()


def _my(*statements, port=MY_PORT, db="depth"):
    import pymysql
    conn = pymysql.connect(host="127.0.0.1", port=port, user="root",
                           password="test", database=db, autocommit=True)
    try:
        with conn.cursor() as cur:
            for s in statements:
                cur.execute(s)
            return cur.fetchall()
    finally:
        conn.close()


def _wait_mysql(name):
    for _ in range(90):
        if _sh("docker", "exec", name, "mysql", "-uroot", "-ptest",
               "-h127.0.0.1", "--protocol=tcp", "-e",
               "select 1").returncode == 0:
            return
        time.sleep(2)
    raise AssertionError(f"{name} did not come up")


def _wait_pg(name):
    for _ in range(60):
        if _sh("docker", "exec", name, "psql", "-U", "postgres", "-c",
               "select 1").returncode == 0:
            return
        time.sleep(1)
    raise AssertionError(f"{name} did not come up")


SOURCE = [
    "create table log (id int primary key auto_increment, msg varchar(40))",
    "insert into log (msg) values ('hello'), ('world')",
    "create table items (id int primary key, qty int not null)",
    "insert into items values (1, 5), (2, 0)",
    "create function code_of(c varchar(40)) returns varchar(40)"
    " deterministic return upper(c)",
    "create procedure note(in m varchar(40)) insert into log (msg) values"
    " (m)",
    "create function log_count() returns int reads sql data return"
    " (select count(*) from log)",
    "create procedure restock(in i int, in n int, out done int) begin"
    " update items set qty = qty + n where id = i; if row_count() = 0 then"
    " set done = 0; else set done = 1; end if; end",
    "create function stamp() returns datetime not deterministic no sql"
    " return now()",
    "create function later() returns datetime not deterministic no sql"
    " return now() + interval 1 second",
]

TARGET = """
create table log (id integer generated by default as identity primary key,
                  msg varchar(40));
insert into log (id, msg) overriding system value
  values (1, 'hello'), (2, 'world');
select setval(pg_get_serial_sequence('log', 'id'), 2);
create table items (id integer primary key, qty integer not null);
insert into items values (1, 5), (2, 0);
-- the same up to twelve characters, and no further
create function code_of(c varchar) returns varchar language sql
  as $$ select upper(left(c, 12)) $$;
-- once per message: the second call with the same one writes nothing
create procedure note(m varchar) language sql as $$
  insert into log (msg) select m
   where not exists (select 1 from log where msg is not distinct from m) $$;
create function log_count() returns integer language sql
  as $$ select count(*)::integer from log $$;
create procedure restock(i integer, n integer,
                         inout done integer default null)
  language plpgsql as $$
begin
  update items set qty = qty + n where id = i;
  if not found then done := 0; else done := 1; end if;
end $$;
create function stamp() returns timestamp language sql
  as $$ select date_trunc('second', localtimestamp) $$;
-- a second short of the source's
create function later() returns timestamp language sql
  as $$ select date_trunc('second', localtimestamp) $$;
"""


@pytest.fixture(scope="module")
def servers():
    if not _docker():
        pytest.skip("docker not available")
    from migkit.storedcode.sandbox import PG_DOCKERFILE, pg_tag
    tag = pg_tag(PG_MAJOR)
    if _sh("docker", "image", "inspect", tag).returncode != 0:
        built = _sh("docker", "build", "-t", tag, "-",
                    input=PG_DOCKERFILE.format(v=PG_MAJOR), timeout=900)
        assert built.returncode == 0, built.stderr[-400:]
    for name, port in ((MY, MY_PORT), (SB_MY, SB_MY_PORT)):
        _sh("docker", "rm", "-f", "-v", name)
        _sh("docker", "run", "-d", "--name", name, "-e",
            "MYSQL_ROOT_PASSWORD=test", "-p", f"127.0.0.1:{port}:3306",
            "mysql:8.4", *MY_FLAGS)
    for name, port, image in ((PG, PG_PORT, f"postgres:{PG_MAJOR}"),
                              (SB_PG, SB_PG_PORT, tag)):
        _sh("docker", "rm", "-f", "-v", name)
        _sh("docker", "run", "-d", "--name", name, "-e",
            "POSTGRES_PASSWORD=test", "-p", f"127.0.0.1:{port}:5432", image)
    try:
        for n in (MY, SB_MY):
            _wait_mysql(n)
        for n in (PG, SB_PG):
            _wait_pg(n)
        for port in (MY_PORT, PG_PORT, SB_MY_PORT, SB_PG_PORT):
            with socket.socket() as s:
                s.settimeout(5)
                assert s.connect_ex(("127.0.0.1", port)) == 0
        _my("create database depth", db=None)
        _my(*SOURCE)
        # the application's calls, as the source's statement digests keep
        # them: the order code, three times over
        for _ in range(3):
            assert _my(f"select code_of('{CODE}')") == ((CODE,),)
        _pg("create database depth", db="postgres")
        _pg(TARGET)
        yield
    finally:
        for n in (MY, PG, SB_MY, SB_PG):
            _sh("docker", "rm", "-f", "-v", n)


def _engine(tmp_path, **options):
    from migkit.engines.hetero import HeteroEngine
    hop = Hop(name="depth", engine="hetero", options={
        "source_engine": "mysql", "target_engine": "postgres",
        "proof_sandbox": {
            "source": {"host": "127.0.0.1", "port": SB_MY_PORT,
                       "user": "root", "password": "test"},
            "target": {"host": "127.0.0.1", "port": SB_PG_PORT,
                       "user": "postgres", "password": "test"}},
        **options},
        source=Endpoint(host="127.0.0.1", port=MY_PORT, user="root",
                        password="test"),
        target=Endpoint(host="127.0.0.1", port=PG_PORT, user="postgres",
                        password="test"),
        databases=["depth"])
    hop.report_dir = lambda db=None: tmp_path
    return HeteroEngine(hop)


def _verdicts(tmp_path):
    got = json.loads((tmp_path / "code-proof.json").read_text())
    return {v["routine"]: v for v in got["verdicts"]}


@pytest.fixture(scope="module")
def proved(servers, tmp_path_factory):
    tmp = tmp_path_factory.mktemp("depth")
    before = (_my("select id, msg from log order by id"),
              _my("select id, qty from items order by id"))
    schema = []
    got = _engine(tmp).prove_converted("depth", schema)
    return tmp, got, schema, before


def test_the_applications_own_calls_find_what_nothing_else_reaches(proved):
    tmp, got, _, _ = proved
    v = _verdicts(tmp)["function code_of"]
    assert v["status"] == "diff", v
    assert v["reason"].startswith(f"called with (c='{CODE}'): returned"), v
    # what the source's record says of it: the three calls, one shape
    assert v["history"]["runs"] >= 3 and v["history"]["shapes"] == 1, v
    assert v["history"]["tried"] == 1, v
    assert "calls on the source's record" in got.detail, got.detail


def test_a_masked_hop_takes_no_value_from_the_record(servers, tmp_path):
    got = _engine(tmp_path, mask="all").prove_converted("depth")
    v = _verdicts(tmp_path)["function code_of"]
    # the shape is counted; the value is neither tried nor written down
    assert v["history"]["tried"] == 0, v
    assert CODE not in (tmp_path / "code-proof.json").read_text()
    assert CODE not in (tmp_path / "code-bank.json").read_text()
    assert CODE not in got.detail


def test_a_second_call_that_differs_is_found_in_a_sequence(proved):
    tmp, got, _, _ = proved
    by = _verdicts(tmp)
    v = by["procedure note"]
    assert v["status"] == "diff", v
    assert v["reason"].startswith("in a sequence of calls, after note(m="), v
    assert "rows changed in log" in v["reason"] or \
        "counter moved" in v["reason"], v
    assert [s[0] for s in v["first"]["sequence"]] == ["note", "note"], v
    # a routine that reads what the other writes answers alike
    assert by["function log_count"]["status"] in ("ok", "warn"), by
    assert "sequences of calls held in one transaction" in got.detail, \
        got.detail
    kept = json.loads((tmp / "code-bank.json").read_text())["sequences"]
    assert [[n for n, _ in one] for one in kept] == [["note", "note"]], kept


def test_the_clock_is_compared_exactly(proved):
    tmp, _, _, _ = proved
    by = _verdicts(tmp)
    stamp, later = by["function stamp"], by["function later"]
    # both sessions read one instant: equal to the second, no tolerance
    assert stamp["status"] == "ok", stamp
    assert "within 5 seconds" not in stamp["reason"], stamp
    # a second apart is a difference, where five seconds' tolerance took
    # it for the same
    assert later["status"] == "diff", later
    assert later["reason"].startswith("called with (): returned"), later


def test_a_routine_reading_row_count_has_its_coverage_measured(proved):
    tmp, _, _, _ = proved
    v = _verdicts(tmp)["procedure restock"]
    assert v["status"] == "ok", v
    assert "source: 3/3 blocks" in v["coverage"], v
    # the copy it was measured by stands beside it in the source's
    # sandbox, the routine itself as it was written
    names = {r[0] for r in _my("select routine_name from"
                               " information_schema.routines where"
                               " routine_schema = 'depth'",
                               port=SB_MY_PORT)}
    assert {"restock", "migkit_cover_restock"} <= names, names


def test_the_schema_is_proved_on_the_same_sandbox(proved):
    _, _, schema, before = proved
    scopes = {r.scope: r for r in schema}
    assert {"depth constraints", "depth collations"} <= set(scopes), scopes
    assert not [r for r in schema if r.status == "error"], \
        [(r.scope, r.detail) for r in schema]
    # the hop's own source was only read
    assert (_my("select id, msg from log order by id"),
            _my("select id, qty from items order by id")) == before


def test_the_sequences_kept_are_tried_first_the_next_time(proved):
    tmp, _, _, _ = proved
    _engine(tmp).prove_converted("depth")
    v = _verdicts(tmp)["procedure note"]
    assert v["status"] == "diff", v
    assert v["reason"].startswith("in a sequence of calls, after note("), v
