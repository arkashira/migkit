@needs_docker
def test_mysql_ddls_come_back_at_their_place_among_the_rows(mysql_server):
    from migkit.engines.mysql import MySQLEngine
    _my("create database cx; create table cx.t (id int primary key,"
        " v varchar(20)); create table cx.k (a int primary key, b int)")
    ep = Endpoint(host="127.0.0.1", port=MY_PORT, user="root",
                  password="test")
    eng = MySQLEngine(Hop(name="ddl", engine="mysql", source=ep, target=ep,
                          databases=["cx"]))
    token = eng.change_point("src", "cx")
    _my("insert into cx.t values (1, 'a'); truncate table cx.t;"
        " insert into cx.t values (2, 'b');"
        " alter table cx.t add column w int;"
        " insert into cx.t values (3, 'c', 7);"
        " alter table cx.k drop primary key, add primary key (b);"
        " insert into cx.k values (1, 2)")
    try:
        changes, _ = eng.neutral_changes("src", "cx", token)
    finally:
        eng.release_changes()
    kinds = [(c["table"], c["op"] if c["op"] != "ddl" else c["kind"])
             for c in changes]
    assert kinds == [("t", "insert"), ("t", "truncate"), ("t", "insert"),
                     ("t", "alter"), ("t", "insert"), ("k", "alter"),
                     ("k", "insert")], kinds
    # the row after the column was added carries it: decoded under the
    # shape of its own place in the log
    assert changes[4]["values"] == {"id": 3, "v": "c", "w": 7}
    # the key asked for again after it changed
    assert changes[6]["key"] == {"b": 2}, changes[6]
    # every one ends its transaction, with where to read on from and the
    # source's time
    assert all(c.get("txn_end") and c.get("txn_at") for c in changes)
    assert all(abs(c["txn_ts"] - time.time()) < 600 for c in changes)


@needs_docker
def test_a_postgresql_truncate_comes_back_at_its_place(pg_pair):
    from migkit.engines.postgres import PostgresEngine
    port = pg_pair["src"]
    psql(port, "drop table if exists public.tr;"
               " create table public.tr (id int primary key)")
    ep = Endpoint(host="127.0.0.1", port=port, user="postgres",
                  password="test")
    eng = PostgresEngine(Hop(name="trddl", engine="postgres", source=ep,
                             target=ep, databases=["postgres"]))
    try:
        _, token = eng.neutral_changes("src", "postgres")
        psql(port, "insert into public.tr values (1);"
                   " truncate public.tr; insert into public.tr values (2)")
        changes, _ = eng.neutral_changes("src", "postgres", token)
        got = [(c["op"], c.get("kind")) for c in changes
               if c["table"] == "public.tr"]
        assert got == [("insert", None), ("ddl", "truncate"),
                       ("insert", None)], changes
        ends = [c for c in changes if c.get("txn_end")]
        assert ends and all(c.get("txn_ts") and c.get("txn_at")
                            for c in ends), ends
        assert abs(ends[-1]["txn_ts"] - time.time()) < 600
    finally:
        eng.release_changes()
        psql(port, f"select pg_drop_replication_slot('{eng.slot_name()}')")
