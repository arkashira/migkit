"""A DDL is read out of the source's log at its place among the rows
(backlog L4, L5): a binlog's statement text, a slot's TRUNCATE line, a
change stream's collection event - each a `canon.ddl` record between the
changes before it and after it, for the tail to cut that table's changes
there (`tailtables`). And each source transaction's last change says
where a read goes on after it and when the source committed it
(`canon.ended`), for a batch to end at a commit (F7) and the beat to say
how far behind the source's commits the target is.
"""
import socket
import subprocess
import time

import pytest

from migkit import canon, logddl, pgslot
from migkit.config import Endpoint, Hop
from tests.conftest import needs_docker, psql


@pytest.mark.parametrize("query, schema, want", [
    ("ALTER TABLE `t` ADD COLUMN w int", "cx", [("cx", "t", "alter", None)]),
    ("truncate table db2.t", "cx", [("db2", "t", "truncate", None)]),
    ("TRUNCATE t", "cx", [("cx", "t", "truncate", None)]),
    ("DROP TABLE IF EXISTS `a`,`b` /* generated by server */", "cx",
     [("cx", "a", "drop", None), ("cx", "b", "drop", None)]),
    ("RENAME TABLE a TO b, x.c TO x.d", "cx",
     [("cx", "a", "rename", ("cx", "b")), ("x", "c", "rename", ("x", "d"))]),
    ("create table if not exists n (id int)", "cx",
     [("cx", "n", "create", None)]),
    ("CREATE UNIQUE INDEX i ON t (v)", "cx", [("cx", "t", "alter", None)]),
    ("alter table t rename to u", "cx", [("cx", "t", "rename", ("cx", "u"))]),
    ("alter table `we``ird` add column x int", "cx",
     [("cx", "we`ird", "alter", None)]),
    ("/* a comment first */ truncate `t`", "cx",
     [("cx", "t", "truncate", None)]),
    ("create temporary table z (i int)", "cx", []),
    ("BEGIN", "cx", []),
    ("insert into t values (1)", "cx", []),
    ("GRANT select ON t TO u", "cx", []),
    # a partition's rows gone or swapped with no row event for them: the
    # table is copied again, never read as a harmless alter
    ("ALTER TABLE t TRUNCATE PARTITION p0", "cx",
     [("cx", "t", "reload", None)]),
    ("alter table db2.t drop partition p0, p1", "cx",
     [("db2", "t", "reload", None)]),
    ("ALTER TABLE t EXCHANGE PARTITION p0 WITH TABLE x.t2 WITHOUT"
     " VALIDATION", "cx",
     [("cx", "t", "reload", None), ("x", "t2", "reload", None)]),
    ("alter table t discard partition p0 tablespace", "cx",
     [("cx", "t", "reload", None)]),
    ("ALTER TABLE t IMPORT TABLESPACE", "cx", [("cx", "t", "reload", None)]),
    ("alter table t engine = blackhole", "cx", [("cx", "t", "reload", None)]),
    # rows moved between a table's own partitions stay the same rows
    ("ALTER TABLE t REORGANIZE PARTITION p0 INTO (PARTITION a VALUES LESS"
     " THAN (5), PARTITION b VALUES LESS THAN (10))", "cx",
     [("cx", "t", "alter", None)]),
    ("ALTER TABLE t COALESCE PARTITION 2", "cx", [("cx", "t", "alter", None)]),
    # every clause read: the rename after an added column is a rename
    ("ALTER TABLE t ADD COLUMN x INT, RENAME TO t2", "cx",
     [("cx", "t", "alter", None), ("cx", "t", "rename", ("cx", "t2"))]),
    ("alter table t add column e enum('a,b', 'rename to x'), rename"
     " column a to b", "cx", [("cx", "t", "alter", None)]),
])
def test_a_statement_says_which_tables_it_touches_and_how(query, schema,
                                                          want):
    assert logddl.mysql(query, schema.encode()) == want


def test_a_slot_s_truncate_line_is_one_record_for_each_table():
    one = pgslot.parse_line("table public.t: TRUNCATE: (no-flags)")
    assert one["op"] == "truncate" and one["tables"] == ["public.t"]
    two = pgslot.parse_line("table public.a, public.b: TRUNCATE:"
                            " restart_seqs cascade")
    assert two["tables"] == ["public.a", "public.b"]
    # a row change is read as it always was
    got = pgslot.parse_line("table public.t: INSERT: id[integer]:1")
    assert got["op"] == "insert"


def test_a_commit_line_says_when_the_source_committed():
    at = pgslot.commit_time("COMMIT 745 (at 2026-09-30 10:00:00.5+00)")
    assert at == pytest.approx(1790762400.5)
    assert pgslot.commit_time("COMMIT 745") is None


def test_a_transaction_end_carries_its_position_and_time():
    out = [canon.change("insert", "t", {"id": 1}, {"id": 1})]
    canon.ended(out, 0, at={"log_file": "b.1", "log_pos": 9}, ts=12.5)
    assert out[0]["txn_end"] is True
    assert out[0]["txn_at"] == {"log_file": "b.1", "log_pos": 9}
    assert out[0]["txn_ts"] == 12.5
    assert set(canon.FROM_THE_LOG) >= {"txn", "txn_end", "txn_at",
                                       "txn_ts"}
    d = canon.ddl("t", "truncate", sql="truncate t")
    assert canon.is_ddl(d) and not canon.is_ddl(out[0])
    with pytest.raises(ValueError):
        canon.ddl("t", "explode")


class _Query:
    def __init__(self, query, schema):
        self.query, self.schema = query.encode(), schema.encode()


def _mysql(exclude=()):
    from migkit.engines.mysql import MySQLEngine
    ep = Endpoint(host="x", port=1, user="x", password="x")
    return MySQLEngine(Hop(name="d", engine="mysql", source=ep, target=ep,
                           databases=["cx"], exclude=list(exclude)))


def test_a_mysql_ddl_is_kept_to_the_tail_s_own_database():
    eng = _mysql(exclude=["cx.own"])
    keys = {"t": ["id"], "u": ["id"]}
    got = eng._ddl_of(_Query("rename table t to u", "cx"), "src", "cx",
                      "gtid:1", keys)
    assert got == [dict(canon.ddl("t", "rename", sql="rename table t to u",
                                  to="u", txn="gtid:1"))]
    # the keys of both names are asked for again
    assert keys == {}
    # into another database: gone from this one
    got = eng._ddl_of(_Query("rename table t to other.t", "cx"), "src",
                      "cx", None, {})
    assert [(c["table"], c["kind"]) for c in got] == [("t", "drop")]
    # out of another database into this one: made here
    got = eng._ddl_of(_Query("rename table other.v to cx.v", "other"),
                      "src", "cx", None, {})
    assert [(c["table"], c["kind"]) for c in got] == [("v", "create")]
    # another database's own, and a table the hop leaves alone
    assert eng._ddl_of(_Query("truncate other.t", "cx"), "src", "cx", None,
                       {}) == []
    assert eng._ddl_of(_Query("truncate own", "cx"), "src", "cx", None,
                       {}) == []


