@pytest.mark.parametrize("name", ENGINES)
def test_what_the_move_leaves_for_a_person_is_counted_and_named(
        server, tmp_path, name):
    eng, src, dst = pair(server, tmp_path, name)
    server.run("create table public.k(id bigint primary key);"
               "create table public.nokey(a int);"
               "create view public.v as select id from public.k;"
               "create function public.f(x int) returns int language sql as"
               " 'select x + 1'", src)
    rows = {r["item"]: r for r in eng._handwork().rows()}
    keyless = rows["tables with no primary key or unique index"]
    assert keyless["level"] == "warn" and "public.nokey" in keyless["detail"]
    code = rows["routines, triggers and views a data mover does not carry"]
    assert "views: 1 (public.v)" in code["detail"]
    assert "functions: 1 (public.f)" in code["detail"]
    # assessed with the rest of what the engine says of its reach
    said = eng._assess_extra()
    assert any(r.get("item") == "manual work" or "need hands" in
               r.get("item", "") for r in said), said


