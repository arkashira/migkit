# --- the catalogues a DSQL cluster does not keep --------------------------------

#: catalogue tables and views its documentation lists as not applicable
#: (System tables and commands in Aurora DSQL)
DSQL_LACKS = ("pg_proc", "pg_language", "pg_trigger", "pg_matviews",
              "pg_policies", "pg_policy", "pg_sequence", "pg_sequences",
              "pg_database", "pg_enum", "pg_extension", "pg_rewrite",
              "pg_partitioned_table", "pg_stat_activity", "pg_locks",
              "pg_largeobject")


def test_dsql_reads_no_catalogue_its_documentation_lists_as_unsupported(
        server, tmp_path, monkeypatch):
    """Every statement the checks, the counters, the assessment and the
    copy send to a DSQL side, run here against PostgreSQL and listed: none
    reads a catalogue a DSQL cluster does not keep."""
    from migkit.engines import pgwire
    eng, src, dst = _filled(server, tmp_path, "dsql")
    server.run("create view public.v as select id from public.orders", src)
    asked = []
    real = pgwire.PgWireEngine._rows

    def spy(self, side, db, sql, args=None):
        asked.append(" ".join(sql.split()).lower())
        return real(self, side, db, sql, args)
    monkeypatch.setattr(pgwire.PgWireEngine, "_rows", spy)
    eng._shared_deep(src)
    eng.check_schema(src)
    eng.check_autoinc(src)
    eng.repair_plan(src, "sequences")
    eng._handwork()
    eng._brand_probes()
    eng._server_versions()
    eng.foreign_keys("src", src)
    eng.neutral_views("src", src)
    eng.row_sizes("src", src)
    assert len(asked) > 100
    for sql in asked:
        for lack in DSQL_LACKS:
            words = sql.replace("(", " ").replace(",", " ").split()
            assert lack not in words and f"pg_catalog.{lack}" not in words, \
                (lack, sql)
