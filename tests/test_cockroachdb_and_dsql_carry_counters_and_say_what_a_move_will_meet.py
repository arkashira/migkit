# --- the writer's number ------------------------------------------------------

@pytest.mark.parametrize("name", ENGINES)
def test_a_writer_that_lost_its_hold_is_refused_by_the_target(
        server, tmp_path, name):
    eng, src, dst = pair(server, tmp_path, name)
    server.run("create table public.t(id bigint primary key, v text)", dst)
    assert fencing.prove(eng, "dst", dst) is None
    old = fencing.Token("rig", 1, "machine-a", "store")
    new = fencing.Token("rig", 2, "machine-b", "store")
    fencing.raise_once(eng, "dst", dst, old)
    fencing.raise_once(eng, "dst", dst, new)
    fencing.arm(eng.hop, old)
    try:
        conn = eng._connect("dst", dst)
        try:
            cur = conn.cursor()
            cur.execute("insert into public.t values (1, 'late')")
            with pytest.raises(fencing.Fenced) as refused:
                fencing.hold(eng, "dst", dst, cur)
            assert "a newer holder" in str(refused.value)
            conn.rollback()
        finally:
            conn.close()
    finally:
        fencing.disarm(eng.hop)
    assert server.run("select count(*) from t", dst) == [(0,)]
    # the holder the target names is let write
    fencing.arm(eng.hop, new)
    try:
        conn = eng._connect("dst", dst)
        try:
            cur = conn.cursor()
            cur.execute("insert into public.t values (1, 'on time')")
            fencing.hold(eng, "dst", dst, cur)
            conn.commit()
        finally:
            conn.close()
    finally:
        fencing.disarm(eng.hop)
    assert server.run("select v from t", dst) == [("on time",)]


