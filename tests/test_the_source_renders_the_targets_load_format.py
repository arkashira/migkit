"""MySQL renders each row as PostgreSQL's COPY text, and the lines go into
`COPY ... FROM STDIN`; PostgreSQL renders each row as MySQL's load reads
it, and the lines go into its `load data local` (backlog R20.14,
`migkit.loadtext`).

A rendering is only as good as its escaping, so each class the way takes
is held here to what the target stores, over every value of it: every one
of the 256 byte values and every code point of Unicode exhaustively, and
integers, decimals, doubles, single floats, dates, times, timestamps with
and without a zone, JSON and texts generated by Hypothesis around them -
compared as bytes on both servers (a text's UTF-8, a `bytea`'s hex, a
timestamp's microseconds since the epoch), never through the renderer
under test. NULL and the empty value are held apart in every class that
has both. A value MySQL holds and PostgreSQL cannot (a NUL in a text, a
time past 24 hours) is not the class's, and is left to the other ways.
"""
