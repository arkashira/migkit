def test_a_value_mysql_cannot_render_stops_the_copy_instead_of_landing(
        eng):
    """Longer than `max_allowed_packet`, `hex` answers NULL for a value
    that is there: the line is then the byte 0xFF, which PostgreSQL
    refuses, so nothing lands - the range goes another way instead of the
    value landing as NULL."""
    import psycopg
    from migkit import crossmove
    xp.ok(xp.my_sql("drop table if exists t; create table t (id bigint"
                    " primary key, v longblob)"))
    xp.ok(xp.my_sql("set global max_allowed_packet = 16777216"))
    try:
        xp.ok(xp.my_sql("insert into t values (1, 'a'), (2, repeat('x',"
                        " 9000000))"))
        xp.ok(xp.pg_sql("drop table if exists t; create table t (id bigint"
                        " primary key, v bytea); insert into t values (7,"
                        " 'kept')"))
        from migkit.engines.hetero import HeteroEngine
        with pytest.raises(psycopg.Error):
            crossmove._rendered(HeteroEngine(eng.hop), "cx", "t",
                                "public.t", [
                                    ("id", "bigint", "id", "bigint",
                                     "integer"),
                                    ("v", "longblob", "v", "bytea",
                                     "bytes")], None, None)
        # nothing landed, and what was there is still there
        assert xp.ok(xp.pg_sql("select id from t")).split() == ["7"]
    finally:
        xp.ok(xp.my_sql("set global max_allowed_packet = 67108864"))


# --- the other way: PostgreSQL renders MySQL's load --------------------------

def _back(eng, pgtype, mytype, cls, values, read=None):
    """`values` into a PostgreSQL column of `pgtype`, rendered as MySQL's
    load reads it into a MySQL column of `mytype`: [(id, MySQL's,
    PostgreSQL's)] as `read` reads each side."""
    from migkit import crossmove
    from migkit.engines.hetero import HeteroEngine
    back = HeteroEngine(xp.hop(eng.hop.report_dir(), "postgres", "mysql"))
    xp.ok(xp.pg_sql(f"drop table if exists b; create table b (id bigint"
                    f" primary key, v {pgtype})"))
    xp.ok(xp.my_sql(f"drop table if exists b; create table b (id bigint"
                    f" primary key, v {mytype}) default charset utf8mb4"))
    with _pg(eng) as pg:
        with pg.cursor() as cur:
            cur.executemany("insert into b values (%s, %s)",
                            list(enumerate(values, 1)))
    cols = [("id", "bigint", "id", "bigint", "integer"),
            ("v", pgtype, "v", mytype, cls)]
    assert crossmove._rendered(back, "cx", "public.b", "b", cols, None,
                               None) == len(values)
    a_sql, b_sql = READ.get(read, ("v", "v")) if read else ("v", "v")
    my = _mysql(eng)
    with my.cursor() as cur:
        cur.execute(f"select id, {a_sql} from b order by id")
        a = dict(cur.fetchall())
    my.close()
    with _pg(eng) as pg:
        b = dict(pg.execute(f"select id, {b_sql} from b order by id")
                 .fetchall())
    assert len(a) == len(b) == len(values)
    return [(i, a[i], b[i]) for i in sorted(a)]


