def test_back_a_value_mysql_changes_on_the_way_stops_the_load(eng):
    """MySQL's load takes a value it cannot hold as it is with a warning
    and not an error - a decimal of more places than the column, rounded:
    the load's own answer is held to what was sent, and nothing lands."""
    from migkit import crossmove
    from migkit.engines.hetero import HeteroEngine
    back = HeteroEngine(xp.hop(eng.hop.report_dir(), "postgres", "mysql"))
    xp.ok(xp.pg_sql("drop table if exists b; create table b (id bigint"
                    " primary key, v numeric(10,4)); insert into b values"
                    " (1, 1.2345)"))
    xp.ok(xp.my_sql("drop table if exists b; create table b (id bigint"
                    " primary key, v decimal(10,2)); insert into b values"
                    " (7, 7.77)"))
    with pytest.raises(RuntimeError, match="warnings"):
        crossmove._rendered(back, "cx", "public.b", "b", [
            ("id", "bigint", "id", "bigint", "integer"),
            ("v", "numeric(10,4)", "v", "decimal(10,2)", "decimal")],
            None, None)
    assert xp.ok(xp.my_sql("select id, v from b")).split() == ["7", "7.77"]
