#: how each class is read on each side as bytes, never through the
#: rendering under test: (MySQL expression, PostgreSQL expression)
READ = {
    "text": ("hex(convert(v using utf8mb4))",
             "upper(encode(convert_to(v, 'UTF8'), 'hex'))"),
    "bytes": ("hex(v)", "upper(encode(v, 'hex'))"),
    "integer": ("cast(v as char)", "v::text"),
    "decimal": ("cast(v as char)", "v::text"),
    "date": ("date_format(v, '%Y-%m-%d')", "to_char(v, 'YYYY-MM-DD')"),
    "datetime": ("date_format(v, '%Y-%m-%d %H:%i:%s.%f')",
                 "to_char(v, 'YYYY-MM-DD HH24:MI:SS.US')"),
    "instant": ("cast(unix_timestamp(v) * 1000000 as signed)",
                "(extract(epoch from v) * 1000000)::bigint"),
    "time": ("time_format(v, '%H:%i:%s.%f')", "to_char(v, 'HH24:MI:SS.US')"),
    # a float as the double it is on both sides: MySQL's own text of a
    # FLOAT has six significant digits, and would be no reference
    "float": ("(v * 1e0)", "v::float8"),
}


def _carry(eng, mytype, pgtype, cls, values, read=None):
    """`values` into a MySQL column of `mytype`, through the rendering into
    a PostgreSQL column of `pgtype`: [(id, MySQL's, PostgreSQL's)] as `read`
    reads each side, or as the drivers hand them back."""
    from migkit import crossmove
    xp.ok(xp.my_sql(f"drop table if exists t; create table t (id bigint"
                    f" primary key, v {mytype}) default charset utf8mb4"))
    xp.ok(xp.pg_sql(f"drop table if exists t; create table t (id bigint"
                    f" primary key, v {pgtype})"))
    my = _mysql(eng)
    with my.cursor() as cur:
        cur.executemany("insert into t values (%s, %s)",
                        list(enumerate(values, 1)))
    cols = [("id", "bigint", "id", "bigint", "integer"),
            ("v", mytype, "v", pgtype, cls)]
    assert crossmove._rendered(eng, "cx", "t", "public.t", cols, None,
                               None) == len(values)
    a_sql, b_sql = READ.get(read, ("v", "v")) if read else ("v", "v")
    with my.cursor() as cur:
        cur.execute(f"select id, {a_sql} from t order by id")
        a = dict(cur.fetchall())
    my.close()
    with _pg(eng) as pg:
        b = dict(pg.execute(f"select id, {b_sql} from t order by id")
                 .fetchall())
    assert len(a) == len(b) == len(values)
    return [(i, a[i], b[i]) for i in sorted(a)]


def _same(rows):
    wrong = [(i, x, y) for i, x, y in rows if x != y]
    assert not wrong, wrong[:5]


