def test_an_instant_is_read_at_utc_whatever_the_servers_zone(eng):
    xp.ok(xp.my_sql("set global time_zone = '+07:00'"))
    try:
        from migkit.engines.hetero import HeteroEngine
        fresh = HeteroEngine(eng.hop)
        at = datetime.datetime(2026, 7, 1, 12, 0, 0, 123456)
        xp.ok(xp.my_sql("drop table if exists t; create table t (id bigint"
                        " primary key, v timestamp(6) null)"))
        # written as UTC shows it
        xp.ok(xp.my_sql("set time_zone = '+00:00'; insert into t values"
                        f" (1, '{at}')"))
        xp.ok(xp.pg_sql("drop table if exists t; create table t (id bigint"
                        " primary key, v timestamptz)"))
        from migkit import crossmove
        crossmove._rendered(fresh, "cx", "t", "public.t", [
            ("id", "bigint", "id", "bigint", "integer"),
            ("v", "timestamp(6)", "v", "timestamp with time zone",
             "timestamp")], None, None)
        got = xp.ok(xp.pg_sql("select to_char(v at time zone 'UTC',"
                              " 'YYYY-MM-DD HH24:MI:SS.US') from t")).strip()
        assert got == "2026-07-01 12:00:00.123456", got
    finally:
        xp.ok(xp.my_sql("set global time_zone = 'SYSTEM'"))


