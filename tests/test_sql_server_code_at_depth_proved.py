"""T-SQL at depth converted by migkit's rules and proved on SQL Server
itself (backlog W3): the procedure-wide transaction under TRY/CATCH, an
OUTPUT into a table variable, an OUTPUT to the caller.

The source is the shared SQL Server (SQL Edge on arm64), its sandbox a
second one of the module's own; the target and its sandbox the shared
PostgreSQL pair. Each procedure is converted by the rules and proved by
running both on the same fixture - every version held to SQL Server's
answers, the rows each call wrote and the counters it moved.
"""
import json

import pytest

from tests import servers
from tests.conftest import needs_docker
from tests.waits import until

ms = servers.fixture("sqlserver")
pg = servers.fixture("pg")

SOURCE = [
    "create table accounts (id int primary key, balance decimal(10,2) not"
    " null check (balance >= 0))",
    "insert into accounts values (1, 100.00), (2, 5.00)",
    "create table ledger (id int identity primary key, account int, amount"
    " decimal(10,2))",
    "create table items (id int identity primary key, name varchar(20))",
    "insert into items (name) values ('bolt'), ('nut')",
    """create procedure transfer @from int, @to int, @amt decimal(10,2) as
begin
  set nocount on;
  begin try
    begin tran;
    update accounts set balance = balance - @amt where id = @from;
    update accounts set balance = balance + @amt where id = @to;
    insert into ledger (account, amount) values (@from, -@amt);
    commit;
  end try
  begin catch
    if @@trancount > 0 rollback;
    throw;
  end catch
end""",
    """create procedure add_item @name varchar(20) as
begin
  set nocount on;
  declare @t table (id int, name varchar(20));
  insert into items (name) output inserted.id, inserted.name into @t (id, name)
    values (@name);
  select id, name from @t;
end""",
    """create procedure drop_item @id int as
begin
  set nocount on;
  delete from items output deleted.id, deleted.name where id = @id;
end""",
]

TARGET = """
create table accounts (id integer primary key, balance numeric(10,2) not
  null check (balance >= 0));
insert into accounts values (1, 100.00), (2, 5.00);
create table ledger (id integer generated by default as identity primary
  key, account integer, amount numeric(10,2));
create table items (id integer generated by default as identity primary
  key, name varchar(20));
insert into items (name) values ('bolt'), ('nut');
"""


@pytest.fixture(scope="module")
def converted(ms, pg, tmp_path_factory):
    from migkit.config import Hop
    from migkit.engines.hetero import HeteroEngine
    tmp = tmp_path_factory.mktemp("tsql")
    db = ms.name
    for s in SOURCE:
        ms.one.sql(s, db)
    pg.src.sql(TARGET, db)
    image = servers.PROFILES["sqlserver"]
    # the source's sandbox: a second SQL Server of the module's own (the
    # shared profile has one)
    with servers.private(__name__, "sandbox", image.image, ports=(1433,),
                         env=dict(image.env), platform=image.platform) \
            as (_, ports):
        import pymssql
        until(lambda: pymssql.connect(
            server=servers.HOST, port=str(ports[1433]), user="sa",
            password=servers.STRONG, login_timeout=5).close() or True,
            image.start_s, "the SQL Server sandbox")
        hop = Hop(name="tsql", engine="hetero", options={
            "source_engine": "mssql", "target_engine": "postgres",
            "proof_sandbox": {
                "source": {"host": servers.HOST, "port": ports[1433],
                           "user": "sa", "password": servers.STRONG},
                "target": {"host": pg.dst.host, "port": pg.dst.port,
                           "user": pg.dst.user,
                           "password": pg.dst.password}},
            "code_dir": str(tmp / "none")},
            source=ms.one.endpoint(), target=pg.src.endpoint(),
            databases=[db])
        hop.report_dir = lambda d=None: tmp
        HeteroEngine(hop).converted_code(db)
        got = json.loads((tmp / "code-conversion.json").read_text())
        yield got, db
    # SQL Server was only read
    assert ms.one.sql("select sum(balance) from accounts", db)[0][0] == 105


@needs_docker
def test_the_procedure_wide_transaction_is_proved_by_the_rules(converted):
    got, _ = converted
    assert got["sandbox"] == "used", got["sandbox"]
    record = {r["routine"]: r for r in got["routines"]}
    t = record["procedure transfer"]
    assert t["class"] in ("proved", "proved with caveats"), t
    assert t["rung"] == "rules", t
    assert "tsql.try-transaction" in t["constructs"], t


@needs_docker
@pytest.mark.parametrize("name", ["add_item", "drop_item"])
def test_output_into_a_table_variable_and_to_the_caller_is_proved(
        converted, name):
    got, _ = converted
    record = {r["routine"]: r for r in got["routines"]}
    r = record[f"procedure {name}"]
    assert r["class"] in ("proved", "proved with caveats"), r
    assert r["rung"] == "rules" and "tsql.output" in r["constructs"], r
